#!/usr/bin/env node

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, '..');
const envPath = join(rootDir, '.env');
const outputPath = join(rootDir, 'src', 'config', 'public-env.generated.js');

function parseEnv(content) {
  const env = {};
  const lines = content.split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const match = trimmed.match(/^([^=]+)=(.*)$/);
    if (match) {
      const key = match[1].trim();
      let value = match[2].trim();
      // Remove quotes if present
      if ((value.startsWith('"') && value.endsWith('"')) || 
          (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      env[key] = value;
    }
  }
  return env;
}

let mapboxToken = '';

// Try to read from .env first
if (existsSync(envPath)) {
  try {
    const envContent = readFileSync(envPath, 'utf-8');
    const env = parseEnv(envContent);
    mapboxToken = env.MAPBOX_TOKEN || '';
    
    if (mapboxToken) {
      console.log('✓ MAPBOX_TOKEN encontrado en .env');
    } else {
      console.warn('⚠ MAPBOX_TOKEN no encontrado en .env');
    }
  } catch (err) {
    console.error('Error leyendo .env:', err.message);
  }
}

// Fallback: try to read from config.js if no token from .env
if (!mapboxToken) {
  const configPath = join(rootDir, 'src', 'config.js');
  if (existsSync(configPath)) {
    try {
      const configContent = readFileSync(configPath, 'utf-8');
      const tokenMatch = configContent.match(/MAPBOX_TOKEN\s*=\s*["']([^"']+)["']/);
      if (tokenMatch && tokenMatch[1]) {
        mapboxToken = tokenMatch[1];
        console.log('✓ MAPBOX_TOKEN encontrado en src/config.js (fallback)');
      }
    } catch (err) {
      console.error('Error leyendo config.js:', err.message);
    }
  }
}

// Final warning if still no token
if (!mapboxToken) {
  console.warn('⚠ Archivo .env no encontrado - los mapas no funcionarán');
  console.warn('  Crea un archivo .env en la raíz con: MAPBOX_TOKEN=tu_token_aqui');
}

const output = `// Auto-generated by scripts/generate-public-env.js
// Do not edit manually

export const MAPBOX_TOKEN = ${JSON.stringify(mapboxToken)};

if (!MAPBOX_TOKEN) {
  console.error(
    '❌ MAPBOX_TOKEN no configurado. Crea un archivo .env en la raíz del proyecto con:\\n' +
    '   MAPBOX_TOKEN=tu_token_aqui'
  );
}
`;

try {
  writeFileSync(outputPath, output, 'utf-8');
  console.log(`✓ Generado: ${outputPath}`);
} catch (err) {
  console.error('Error escribiendo archivo de configuración:', err.message);
  process.exit(1);
}

